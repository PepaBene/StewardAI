/** Provenance for a sample observation or claim at a cutoff, mirroring `GET /disclosures/provenance`. */
export function sampleProvenance(kind: "observation" | "claim", id: number): Provenance | null {
  const row = kind === "observation" ? SAMPLE_OBSERVATIONS.find((o) => o.id === id) : SAMPLE_CLAIMS.find((c) => c.id === id);
  if (!row) return null;
  const doc = SAMPLE_FILINGS.find((f) => f.version_id === row.document_version_id);
  if (!doc) return null;
  const chain = SAMPLE_FILINGS.filter((f) => f.document_id === doc.document_id).map((f) => ({
    id: f.version_id,
    content_hash: f.content_hash,
    accepted_at: f.accepted_at,
    filed_at: f.filed_at,
    known_at: f.known_at,
    superseded_by_id: f.superseded_by_id,
    is_current: f.is_current,
  }));
  return {
    id,
    kind,
    review_state: row.review_state,
    document_version_id: doc.version_id,
    regulator: doc.regulator,
    external_id: doc.external_id,
    stable_url: doc.stable_url,
    form: doc.form,
    fiscal_period: doc.fiscal_period,
    content_hash: doc.content_hash,
    evidence: row.evidence,
    table_name: row.evidence.quote?.includes("|") ? "Segment and cash flow table" : null,
    row_ref: row.evidence.quote?.includes("|") ? "row 2" : null,
    extraction_method: kind === "observation" ? "ix:nonFraction" : "rule: customer concentration phrase",
    span_parser_version: "disclosure-html-1",
    confidence: kind === "claim" ? 0.58 : 1,
    version_chain: chain,
    envelope: row.envelope,
  };
}
